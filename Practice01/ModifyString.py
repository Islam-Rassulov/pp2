#Example 1 UpperCase
a = "Hello, World!"
print(a.upper())

#Example 2 LowerCase
a = "Hello, World!"
print(a.lower())

#Example 3 Remove WhiteSpace
a = " Hello, World! "
print(a.strip()) # returns "Hello, World!"

#Example 4 Replace String
a = "Hello, World!"
print(a.replace("H", "J"))

#Example 5 String Concatenation
a = "Hello"
b = "World"
c = a + b
print(c)
